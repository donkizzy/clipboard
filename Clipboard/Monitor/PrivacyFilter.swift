import Foundation

/// What capture should and shouldn't record. Built from `Preferences` on
/// the main actor and handed to the monitor as a value.
struct CapturePolicy: Sendable, Equatable {
    var isPaused = false
    /// Honour `org.nspasteboard.ConcealedType` (passwords). On, and locked on
    /// in Settings by default.
    var ignoresConcealed = true
    var ignoredBundleIDs: Set<String> = CapturePolicy.defaultIgnoredBundleIDs

    static let defaultIgnoredBundleIDs: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
    ]
}

/// Implements the nspasteboard.org conventions for marking sensitive or
/// throwaway clipboard contents, plus the per-app ignore list.
enum PrivacyFilter {
    enum Reason: Equatable, Sendable {
        case paused
        case concealed
        case transient
        case autoGenerated
        case ignoredApp(String)
    }

    static let concealedType = "org.nspasteboard.ConcealedType"
    static let transientType = "org.nspasteboard.TransientType"
    static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    /// Older or vendor-specific markers with the same meaning.
    static let legacyConcealedTypes: Set<String> = [
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Returns why the item must be skipped, or `nil` to capture it.
    /// Called with the pasteboard's types *before* any contents are read.
    static func skipReason(types: [String], sourceBundleID: String?, policy: CapturePolicy) -> Reason? {
        if policy.isPaused { return .paused }
        let types = Set(types)
        if types.contains(transientType) { return .transient }
        if types.contains(autoGeneratedType) { return .autoGenerated }
        if policy.ignoresConcealed, types.contains(concealedType) || !types.isDisjoint(with: legacyConcealedTypes) {
            return .concealed
        }
        if let sourceBundleID, policy.ignoredBundleIDs.contains(sourceBundleID) {
            return .ignoredApp(sourceBundleID)
        }
        return nil
    }
}
